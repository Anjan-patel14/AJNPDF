import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = process.cwd();
const sitemapFile = path.join(root, 'src/app/sitemap.ts');
const idsFile = path.join(root, 'scripts/r13-public-tool-ids.json');
const output = path.join(root, 'src/generated/sitemap-lastmod.ts');

const git = (args) => {
  try {
    return execFileSync('git', args, {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return '';
  }
};

const src = fs.readFileSync(sitemapFile, 'utf8');
const staticPaths = [...src.matchAll(/\{\s*path:\s*'([^']+)'/g)].map((match) => match[1]);
const ids = JSON.parse(fs.readFileSync(idsFile, 'utf8'));
const normalize = (value) => (!value || value === '/' ? '/' : `/${value.replace(/^\/+|\/+$/g, '')}`);

const existingText = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '';
const existingFallback = existingText.match(/SITEMAP_FALLBACK_LASTMOD\s*=\s*["']([^"']+)["']/)?.[1] || '';
const existingEntries = new Map(
  [...existingText.matchAll(/^\s*"([^"]+)":\s*"([^"]+)"/gm)].map((match) => [match[1], match[2]]),
);

const head = git(['show', '-s', '--format=%cI', 'HEAD']);
if (!head && !existingFallback) {
  throw new Error('Git history unavailable and no usable sitemap lastmod fallback exists.');
}

const fallback = head || existingFallback;
const entries = new Map();

for (const route of staticPaths) {
  const pathname = normalize(route);
  entries.set(pathname, head || existingEntries.get(pathname) || fallback);
}

for (const id of ids) {
  const pathname = `/${id}`;
  entries.set(pathname, head || existingEntries.get(pathname) || fallback);
}

if (!head) {
  console.warn('WARN: Git history unavailable; preserved existing dates and backfilled missing sitemap routes from the existing fallback.');
}

const lines = [
  '// AUTO-GENERATED by scripts/generate-sitemap-lastmod.mjs.',
  `export const SITEMAP_FALLBACK_LASTMOD = ${JSON.stringify(fallback)};`,
  'export const SITEMAP_LASTMOD: Record<string, string> = {',
  ...[...entries]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([pathname, date]) => `  ${JSON.stringify(pathname)}: ${JSON.stringify(date)},`),
  '};',
  '',
  'export function getSitemapLastModified(pathname: string): string {',
  '  const normalized = !pathname || pathname === "/" ? "/" : `/${pathname.replace(/^\\/+|\\/+$/g, "")}`;',
  '  return SITEMAP_LASTMOD[normalized] || SITEMAP_FALLBACK_LASTMOD;',
  '}',
  '',
];

fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, lines.join('\n'), 'utf8');
console.log(`PASS: sitemap lastmod manifest generated for ${entries.size} canonical routes.`);
