const byLanguage: Partial<Record<LanguageCode, ToolLocaleMap>> = { hi, te, ta, kn };

export function getLocalizedTool(language: LanguageCode, id: string, fallbackName: string, fallbackDesc: string, fallbackKeywords: string[] = []) {
  const entry = byLanguage[language]?.[id];
  if (!entry) return { name: fallbackName, desc: fallbackDesc, aliases: fallbackKeywords };
  return { name: entry.name, desc: entry.desc, aliases: [entry.name, fallbackName, ...(entry.aliases ?? []), ...fallbackKeywords] };
}

export function translateToolExact(language: LanguageCode, text: string): string | undefined {
  if (language === 'en') return undefined;
  const map = byLanguage[language];
  if (!map) return undefined;
  for (const entry of Object.values(map)) {
    if (entry.name === text || entry.desc === text) return text;
  }
  return undefined;
}

